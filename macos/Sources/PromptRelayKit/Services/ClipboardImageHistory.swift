import AppKit
import CryptoKit
import ImageIO
import Observation
import UniformTypeIdentifiers

/// The optional history of the last five images on the clipboard (ADR-014).
///
/// Off by default. While off nothing is polled. While on, a 1 s timer (with
/// tolerance, paused while the displays sleep) reads only
/// `NSPasteboard.changeCount`; when it changes, only the item *types* are
/// looked at, and image bytes are read only for images. Text is never read.
/// Items marked concealed or transient (password managers, nspasteboard.org)
/// and Prompt Relay's own copies are skipped.
@MainActor
@Observable
public final class ClipboardImageHistory {
    public struct Item: Codable, Identifiable, Equatable, Sendable {
        public let id: String
        public let storedFilename: String
        /// The file's name when an image file was copied; else nil.
        public let originalName: String?
        public let byteCount: Int
        public let sha256: String
        public var capturedAt: Date
        public var displayName: String { originalName ?? "Screenshot" }
    }

    public static let limit = 5
    public static let maxBytes = 20 * 1024 * 1024
    public static let ownType = NSPasteboard.PasteboardType("com.promptrelay.origin")
    static let skippedTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.ConcealedType"), .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"), ownType,
    ]

    public private(set) var items: [Item] = []
    public private(set) var isEnabled = false
    /// A plain-language note when an image could not be kept.
    public private(set) var message: String?
    /// How long images are kept.
    public var retention: TimeInterval = 24 * 3600 {
        didSet { prune(); persist() }
    }

    public let folder: URL
    private let pasteboard: NSPasteboard
    private var timer: Timer?
    private var lastChange: Int
    private var sleepObservers: [NSObjectProtocol] = []
    private let fm = FileManager.default

    public init(folder: URL, pasteboard: NSPasteboard = .general) {
        self.folder = folder
        self.pasteboard = pasteboard
        lastChange = pasteboard.changeCount
        items = Self.load(folder)
        prune()
    }

    public static func live(dataDirectory: URL) -> ClipboardImageHistory {
        ClipboardImageHistory(folder: dataDirectory.appendingPathComponent("app/clipboard", isDirectory: true))
    }

    deinit { MainActor.assumeIsolated { timer?.invalidate() } }

    // MARK: On / off

    public func setEnabled(_ on: Bool) {
        guard on != isEnabled else { return }
        isEnabled = on
        if on { start() } else { stop() }
    }

    var isPolling: Bool { timer != nil }

    private func start() {
        lastChange = pasteboard.changeCount   // what was there before is not captured
        scheduleTimer()
        let center = NSWorkspace.shared.notificationCenter
        sleepObservers = [
            center.addObserver(forName: NSWorkspace.screensDidSleepNotification, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { self?.timer?.invalidate(); self?.timer = nil }
            },
            center.addObserver(forName: NSWorkspace.screensDidWakeNotification, object: nil, queue: .main) { [weak self] _ in
                MainActor.assumeIsolated { if self?.isEnabled == true { self?.scheduleTimer() } }
            },
        ]
    }

    private func scheduleTimer() {
        guard timer == nil else { return }
        let timer = Timer(timeInterval: 1, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.5
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    private func stop() {
        timer?.invalidate()
        timer = nil
        sleepObservers.forEach { NSWorkspace.shared.notificationCenter.removeObserver($0) }
        sleepObservers = []
    }

    // MARK: Capture

    /// One check: cheap unless the clipboard changed and holds an image.
    func poll() {
        guard isEnabled else { return }
        let change = pasteboard.changeCount
        guard change != lastChange else { return }
        lastChange = change
        guard let types = pasteboard.types, !types.contains(where: Self.skippedTypes.contains) else { return }
        if let (data, name) = imageData(types: types) { keep(data, name: name) }
    }

    /// Image bytes and the file name for a copied image file; nil for
    /// anything else. Only image types are read.
    private func imageData(types: [NSPasteboard.PasteboardType]) -> (Data, String?)? {
        if types.contains(.fileURL), let url = (pasteboard.readObjects(forClasses: [NSURL.self],
                                                                       options: [.urlReadingFileURLsOnly: true]) as? [URL])?.first {
            guard let type = UTType(filenameExtension: url.pathExtension), type.conforms(to: .image),
                  let size = try? fm.attributesOfItem(atPath: url.path)[.size] as? Int else { return nil }
            guard size <= Self.maxBytes else { message = "\(url.lastPathComponent) is larger than 20 MB; not kept."; return nil }
            return (try? Data(contentsOf: url)).map { ($0, url.lastPathComponent) }
        }
        for type in [NSPasteboard.PasteboardType.png, .init(UTType.jpeg.identifier), .init(UTType.heic.identifier), .tiff]
        where types.contains(type) {
            guard let data = pasteboard.data(forType: type) else { continue }
            guard data.count <= Self.maxBytes * 3 else { message = "The copied image is too large; not kept."; return nil }
            return (data, nil)
        }
        return nil
    }

    func keep(_ raw: Data, name: String?) {
        guard let png = Self.normalized(raw) else { return }
        guard png.count <= Self.maxBytes else { message = "The copied image is larger than 20 MB; not kept."; return }
        let digest = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        if let i = items.firstIndex(where: { $0.sha256 == digest }) {
            var item = items.remove(at: i)
            item.capturedAt = Date()
            items.insert(item, at: 0)
            persist()
            return
        }
        do {
            try ensureFolder()
            let id = UUID().uuidString.lowercased()
            let stored = "\(id).png"
            let url = folder.appendingPathComponent(stored)
            try png.write(to: url, options: [.atomic])
            try fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: url.path)
            items.insert(Item(id: id, storedFilename: stored, originalName: name, byteCount: png.count, sha256: digest,
                              capturedAt: Date()), at: 0)
            while items.count > Self.limit { delete(items.removeLast()) }
            message = nil
            persist()
        } catch {
            message = "The image could not be saved."
        }
    }

    /// PNG bytes for any decodable image (TIFF screenshots become PNG); JPEG
    /// and HEIC files are kept as PNG too, so every item has one format.
    static func normalized(_ data: Data) -> Data? {
        if data.starts(with: [0x89, 0x50, 0x4E, 0x47]), ReportStore.imageType(of: data) != nil { return data }
        guard let source = CGImageSourceCreateWithData(data as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return nil }
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, image, nil)
        return CGImageDestinationFinalize(dest) ? out as Data : nil
    }

    // MARK: Items

    public func url(for item: Item) -> URL { folder.appendingPathComponent(item.storedFilename) }

    public func remove(_ item: Item) {
        items.removeAll { $0.id == item.id }
        delete(item)
        persist()
    }

    public func clearAll() {
        items.forEach(delete)
        items = []
        persist()
    }

    /// Drops items older than the retention period.
    public func prune(now: Date = Date()) {
        let expired = items.filter { now.timeIntervalSince($0.capturedAt) > retention }
        guard !expired.isEmpty else { return }
        items.removeAll { item in expired.contains { $0.id == item.id } }
        expired.forEach(delete)
        persist()
    }

    private func delete(_ item: Item) {
        try? fm.removeItem(at: url(for: item))
    }

    private var indexURL: URL { folder.appendingPathComponent("index.json") }

    private func ensureFolder() throws {
        try fm.createDirectory(at: folder, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
    }

    private func persist() {
        guard (try? ensureFolder()) != nil, let data = try? JSONEncoder().encode(items) else { return }
        try? data.write(to: indexURL, options: [.atomic])
        try? fm.setAttributes([.posixPermissions: 0o600], ofItemAtPath: indexURL.path)
    }

    static func load(_ folder: URL) -> [Item] {
        guard let data = try? Data(contentsOf: folder.appendingPathComponent("index.json")),
              let items = try? JSONDecoder().decode([Item].self, from: data) else { return [] }
        return items.filter { FileManager.default.fileExists(atPath: folder.appendingPathComponent($0.storedFilename).path) }
    }
}
